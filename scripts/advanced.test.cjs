/* Smoke checks for new trainer; run after compileTraining.cjs. */
'use strict'
const assert=require('node:assert/strict')
const {argsFromCLI}=require('./advanced.cjs')
const {paired,simulate}=require('./arena.cjs')
const weights=require('../.sim-dist/learnedPolicy.js').DEFAULT_WEIGHTS
const quick=argsFromCLI(['--preset','quick','--participants','2,4','--games','3','--seed','15'])
assert.equal(quick.generations,2)
assert.deepEqual(quick.participants,[2,4])
assert.equal(quick.games,3)
assert.equal(quick.seed,15)
const automaticSeed = argsFromCLI(['--preset','quick']).seed
assert(Number.isSafeInteger(automaticSeed) && automaticSeed > 0)
assert.notEqual(automaticSeed, 0)
assert.throws(()=>argsFromCLI(['--participants','1,5']),/participants/)
assert.throws(()=>argsFromCLI(['--rival','invalid']),/rival/)
assert.throws(()=>argsFromCLI(['--population','0']),/population/)
const duel=paired({games:3,seed:154321,players:2,candidate:weights,incumbent:weights,verify:true})
assert.equal(duel.deltaMargin,0)
assert.equal(duel.deltaWinRate,0)
const four=paired({games:2,seed:294321,players:4,candidate:weights,incumbent:weights,verify:true})
assert.equal(four.deltaMargin,0)
assert.equal(four.deltaWinRate,0)
const mixed=paired({games:3,seed:394321,players:2,candidate:weights,incumbent:weights,rival:'mixed',verify:true})
assert.equal(mixed.deltaMargin,0)
assert.equal(mixed.deltaWinRate,0)
const finished=simulate({seed:121212,players:3,side:'B',agents:['incumbent','hard','hard'],candidate:weights,incumbent:weights,verify:true})
assert.equal(finished.length,3)
assert(finished.every(p=>Number.isFinite(p.score)))
console.log('Advanced trainer: parameter, paired-seed, multiplayer and conservation tests passed')
